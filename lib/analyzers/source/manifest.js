/** ArmorBreak source-language analyzers. Parsing is offline, bounded and memory-only. */
import { relative } from 'node:path'
import { checkAbort, makeEvidence, makeMeta, sanitizeText } from '../binary/util.js'

const SOURCE_PARSER_ID = 'typescript-compiler-api'
const SOURCE_EXTENSIONS = new Set(['.js', '.jsx', '.mjs', '.cjs', '.ts', '.tsx', '.mts', '.cts'])
const OTHER_SOURCE_LANGUAGES = new Map(Object.entries({
  '.c': 'C', '.h': 'C/C++', '.cc': 'C++', '.cpp': 'C++', '.cxx': 'C++', '.hpp': 'C++',
  '.rs': 'Rust', '.go': 'Go', '.java': 'Java', '.kt': 'Kotlin', '.kts': 'Kotlin', '.cs': 'C#',
  '.py': 'Python', '.pyw': 'Python', '.php': 'PHP', '.rb': 'Ruby', '.lua': 'Lua', '.sh': 'Shell',
  '.bash': 'Shell', '.zsh': 'Shell', '.ps1': 'PowerShell', '.dart': 'Dart', '.ets': 'ArkTS',
  '.sql': 'SQL', '.html': 'HTML', '.htm': 'HTML', '.css': 'CSS', '.scss': 'SCSS',
  '.graphql': 'GraphQL', '.gql': 'GraphQL', '.tf': 'HCL', '.nix': 'Nix', '.v': 'Verilog',
  '.sv': 'SystemVerilog', '.vhd': 'VHDL', '.vhdl': 'VHDL', '.glsl': 'GLSL', '.wgsl': 'WGSL',
  '.hlsl': 'HLSL', '.sol': 'Solidity', '.move': 'Move',
}))
const LAYER_OPTIONS = Object.freeze({
  test: 'includeTests',
  generated: 'includeGenerated',
  vendor: 'includeVendor',
  'build-output': 'includeBuildOutputs',
})

function hasSourceParserExtension(filePath) {
  const extension = String(filePath).toLowerCase().match(/\.[^.\\/]+$/)?.[0]
  return SOURCE_EXTENSIONS.has(extension)
}

function unsupportedSourceLanguage(filePath) {
  const extension = String(filePath).toLowerCase().match(/\.[^.\\/]+$/)?.[0]
  return OTHER_SOURCE_LANGUAGES.get(extension) ?? null
}

export function sourceLayersForPath(filePath) {
  const path = String(filePath).replace(/\\/g, '/').toLowerCase()
  const segments = path.split('/').filter(Boolean)
  const basename = segments.at(-1) ?? ''
  const layers = []
  if (segments.some((segment) => ['vendor', 'vendors', 'third_party', 'third-party', 'external', 'externals'].includes(segment))) layers.push('vendor')
  if (segments.some((segment) => ['generated', 'gen', 'autogenerated', 'auto-generated'].includes(segment)) || /\.(?:generated|g)\.[^.]+$/.test(basename)) layers.push('generated')
  if (segments.some((segment) => ['test', 'tests', '__tests__', 'spec', 'specs'].includes(segment)) || /\.(?:test|spec)\.[^.]+$/.test(basename)) layers.push('test')
  if (segments.some((segment) => ['dist', 'build', 'out', 'coverage', 'target', 'bin', 'obj', '.next', '.nuxt'].includes(segment))) layers.push('build-output')
  return layers.length ? layers : ['product']
}

function isIncludedByLayer(layers, options) {
  return layers.every((layer) => layer === 'product' || options[LAYER_OPTIONS[layer]] === true)
}

function parserUnavailableResult(capability) {
  const warning = 'Pinned TypeScript parser dependency is unavailable in this runtime; no JS/TS source was parsed.'
  const data = {
    schemaVersion: 'armorbreak.source-symbol-ir/v1',
    parser: { id: SOURCE_PARSER_ID, version: 'UNAVAILABLE' },
    summary: {
      filesProvided: 0,
      filesParsed: 0,
      filesOmitted: 0,
      filesWithSyntaxErrors: 0,
      filesTruncated: 0,
      symbols: 0,
      imports: 0,
      exports: 0,
      references: 0,
      unknownEdges: 0,
      recordsEmitted: 0,
      omittedRecords: 0,
      filesListed: 0,
      sourceCandidates: 0,
      unsupportedLanguageFiles: 0,
      filesExcludedByLayer: 0,
      excludedFileDetailsOmitted: 0,
      unreadableFiles: 0,
      invalidEncodingFiles: 0,
      bytesRead: 0,
      truncatedFiles: 0,
      resultTruncated: false,
    },
    files: [],
    unsupportedFiles: [],
    excludedFiles: [],
    analysis: {
      level: 'S2',
      status: 'UNSUPPORTED',
      warnings: [warning],
      limitsApplied: [],
      coverageNotes: ['The parser package was not loaded; source files were not read.'],
      extraction: 'IN_MEMORY_ONLY_NO_CODE_EXECUTED',
    },
  }
  return {
    summary: warning,
    findings: [],
    evidence: [makeEvidence('源码解析器不可用', 'source-symbol-parser-unavailable', warning, { parser: SOURCE_PARSER_ID, parserVersion: 'UNAVAILABLE', status: 'UNSUPPORTED' })],
    data,
    meta: {
      ...makeMeta(capability, 'source-symbol-ir', { analyzedBytes: 0, source: 'workspace-read', truncated: false }, [warning]),
      parserId: SOURCE_PARSER_ID,
      parserVersion: 'UNAVAILABLE',
      supportLevel: 'S2',
    },
  }
}

function boundedOptions(input = {}, limits = {}) {
  const int = (value, fallback, minimum, maximum) => {
    const parsed = Number(value)
    return Number.isFinite(parsed) ? Math.max(minimum, Math.min(maximum, Math.floor(parsed))) : fallback
  }
  const coreFiles = int(limits.maxItems, 300, 1, 300)
  const coreInputBytes = int(limits.maxInputBytes ?? limits.maxBytes, 32 * 1024 * 1024, 1024, 32 * 1024 * 1024)
  const coreFileReadBytes = int(limits.maxFileReadBytes, 4 * 1024 * 1024, 1, 4 * 1024 * 1024)
  return {
    maxFiles: int(input.maxFiles, 100, 1, Math.min(300, coreFiles)),
    maxScanBytes: int(input.maxScanBytes, Math.min(4 * 1024 * 1024, coreInputBytes), 1024, Math.min(8 * 1024 * 1024, coreInputBytes)),
    maxFileBytes: int(input.maxFileBytes, Math.min(256 * 1024, coreFileReadBytes), 1, Math.min(1024 * 1024, coreFileReadBytes)),
    maxRecords: int(input.maxRecords, Math.min(300, coreFiles), 1, Math.min(300, coreFiles)),
    maxDepth: int(input.maxDepth, 5, 0, 8),
    maxResultBytes: int(limits.maxResultBytes, 256 * 1024, 1024, 256 * 1024),
    includeTests: input.includeTests === true,
    includeGenerated: input.includeGenerated === true,
    includeVendor: input.includeVendor === true,
    includeBuildOutputs: input.includeBuildOutputs === true,
  }
}

export function fitSourceResult(data, maxResultBytes) {
  const maxBytes = Math.max(1024, Math.min(192 * 1024, maxResultBytes))
  const fits = () => Buffer.byteLength(JSON.stringify(data), 'utf8') <= maxBytes
  if (fits()) return data
  data.summary.resultTruncated = true
  data.analysis.status = 'PARTIAL'
  data.analysis.limitsApplied = [...new Set([...data.analysis.limitsApplied, 'maxResultBytes'])]
  data.analysis.warnings = [...new Set([...data.analysis.warnings, `Serialized source IR exceeded ${maxBytes} bytes; deterministic detail records were omitted to fit the result budget.`])].slice(0, 100)
  const fields = [
    ['references', 'references'],
    ['unknownEdges', 'unknownEdges'],
    ['syntaxErrors', null],
    ['symbols', 'symbols'],
    ['imports', 'imports'],
    ['exports', 'exports'],
  ]
  let omitted = 0
  for (let fileIndex = data.files.length - 1; fileIndex >= 0 && !fits(); fileIndex -= 1) {
    const file = data.files[fileIndex]
    for (const [field, summaryField] of fields) {
      while (Array.isArray(file[field]) && file[field].length > 0 && !fits()) {
        file[field].pop()
        omitted += 1
        if (summaryField) data.summary[summaryField] = Math.max(0, data.summary[summaryField] - 1)
        file.coverage.omittedRecords += 1
      }
      if (fits()) break
    }
  }
  while (!fits() && data.files.length > 0) {
    const file = data.files.pop()
    const omittedInFile = ['references', 'unknownEdges', 'syntaxErrors', 'symbols', 'imports', 'exports']
      .reduce((total, field) => total + (Array.isArray(file[field]) ? file[field].length : 0), 0)
    data.summary.symbols = Math.max(0, data.summary.symbols - file.symbols.length)
    data.summary.references = Math.max(0, data.summary.references - file.references.length)
    data.summary.imports = Math.max(0, data.summary.imports - file.imports.length)
    data.summary.exports = Math.max(0, data.summary.exports - file.exports.length)
    data.summary.unknownEdges = Math.max(0, data.summary.unknownEdges - file.unknownEdges.length)
    omitted += omittedInFile
    data.summary.filesOmitted = (data.summary.filesOmitted ?? 0) + 1
  }
  while (!fits() && data.unsupportedFiles.length > 0) data.unsupportedFiles.pop()
  while (!fits() && Array.isArray(data.excludedFiles) && data.excludedFiles.length > 0) {
    data.excludedFiles.pop()
    data.summary.excludedFileDetailsOmitted = (data.summary.excludedFileDetailsOmitted ?? 0) + 1
  }
  while (!fits() && data.analysis.warnings.length > 0) data.analysis.warnings.pop()
  if (!fits()) data.analysis.coverageNotes = []
  data.summary.filesParsed = data.files.length
  data.summary.filesWithSyntaxErrors = data.files.filter((file) => file.syntaxErrorCount > 0).length
  data.summary.filesTruncated = data.files.filter((file) => file.truncated).length
  data.summary.omittedRecords += omitted
  data.summary.recordsEmitted = Math.max(0, data.summary.recordsEmitted - omitted)
  return data
}

function relativePath(root, fullPath) {
  const value = relative(root, fullPath).replace(/\\/g, '/')
  if (!value || value === '.') return '[invalid-relative-path]'
  if (value === '..' || value.startsWith('../') || value.startsWith('/') || /^[A-Za-z]:/.test(value)) return '[path-rejected]'
  return sanitizeText(value, 500)
}

function sortPath(left, right) {
  return left < right ? -1 : left > right ? 1 : 0
}

const capabilities = [
  {
    id: 'source.symbols',
    title: 'JavaScript/TypeScript 符号与引用索引',
    description: '用锁定版本的 TypeScript Compiler API 对 Core 安全枚举的 JS/TS 文件生成 S2 语法/符号 IR、导入导出、源码位置和同文件引用；跨文件解析、类型语义和数据流明确标为未实现。',
    riskLevel: 'L0',
    targetKind: 'directory',
    externalTools: [],
    params: {
      type: 'object',
      properties: {
        maxFiles: { type: 'integer', minimum: 1, maximum: 300 },
        maxScanBytes: { type: 'integer', minimum: 1024, maximum: 8388608 },
        maxFileBytes: { type: 'integer', minimum: 1, maximum: 1048576 },
        maxRecords: { type: 'integer', minimum: 1, maximum: 300 },
        maxDepth: { type: 'integer', minimum: 0, maximum: 8 },
        includeTests: { type: 'boolean' },
        includeGenerated: { type: 'boolean' },
        includeVendor: { type: 'boolean' },
        includeBuildOutputs: { type: 'boolean' },
      },
      additionalProperties: false,
    },
    async run(input) {
      const capability = 'source.symbols'
      checkAbort(input.env, capability)
      if (!input.targetPath || typeof input.env?.listFiles !== 'function' || typeof input.env?.readFile !== 'function') {
        throw new Error('source.symbols requires a directory target and Core-bounded env.listFiles/env.readFile')
      }
      let sourceParser
      try {
        sourceParser = await import('./symbols.js')
      } catch (error) {
        if (error?.code !== 'ERR_MODULE_NOT_FOUND' || !String(error.message).includes("'typescript'")) throw error
        return parserUnavailableResult(capability)
      }
      const limits = boundedOptions(input.options, input.limits)
      const listed = await input.env.listFiles(input.targetPath, { maxFiles: limits.maxFiles, maxDepth: limits.maxDepth })
      const sorted = [...new Set((Array.isArray(listed) ? listed : []).filter((path) => typeof path === 'string'))].sort(sortPath)
      const sourceLayers = new Map(sorted.map((filePath) => [filePath, sourceLayersForPath(filePath)]))
      const excludedFiles = sorted
        .filter((filePath) => !isIncludedByLayer(sourceLayers.get(filePath), limits))
        .map((filePath) => ({ path: relativePath(input.targetPath, filePath), layers: sourceLayers.get(filePath), reason: 'DEFAULT_LAYER_POLICY' }))
      const candidates = sorted.filter((filePath) => hasSourceParserExtension(filePath) && isIncludedByLayer(sourceLayers.get(filePath), limits))
      const unsupportedLanguagePaths = sorted.filter((filePath) => unsupportedSourceLanguage(filePath) && isIncludedByLayer(sourceLayers.get(filePath), limits))
      const units = []
      const unsupportedFiles = []
      let bytesRead = 0
      let unreadableFiles = 0
      let encodingFailures = 0
      let truncatedFiles = 0
      const limitsApplied = []
      const warnings = []
      const utf8 = new TextDecoder('utf-8', { fatal: true })

      for (const filePath of candidates) {
        checkAbort(input.env, capability)
        if (units.length >= limits.maxFiles) {
          limitsApplied.push('maxFiles')
          break
        }
        const remaining = limits.maxScanBytes - bytesRead
        if (remaining <= 0) {
          limitsApplied.push('maxScanBytes')
          break
        }
        const readCap = Math.min(limits.maxFileBytes, remaining)
        let bytes
        try {
          bytes = await input.env.readFile(filePath, readCap)
        } catch {
          unreadableFiles += 1
          unsupportedFiles.push({ path: relativePath(input.targetPath, filePath), reason: 'CORE_READ_FAILED' })
          continue
        }
        if (!Buffer.isBuffer(bytes)) bytes = Buffer.from(bytes ?? [])
        bytesRead += bytes.length
        const truncated = bytes.length === readCap
        if (truncated) {
          truncatedFiles += 1
          limitsApplied.push(bytesRead >= limits.maxScanBytes ? 'maxScanBytes' : 'maxFileBytes')
        }
        let text
        try {
          text = utf8.decode(bytes)
        } catch {
          encodingFailures += 1
          unsupportedFiles.push({ path: relativePath(input.targetPath, filePath), reason: 'INVALID_UTF8' })
          continue
        }
        units.push({ path: relativePath(input.targetPath, filePath), text, truncated, sourceLayers: sourceLayers.get(filePath) })
      }

      const unsupportedLanguageCount = unsupportedLanguagePaths.length
      if (unsupportedLanguageCount > 0) {
        const extensions = [...new Set(unsupportedLanguagePaths.map((filePath) => String(filePath).toLowerCase().match(/\.[^.\\/]+$/)?.[0]))].sort()
        warnings.push(`${unsupportedLanguageCount} source file(s) were not parsed because this M2 slice has no S2 backend for ${extensions.join(', ')}.`)
      }
      if (excludedFiles.length > 0) warnings.push(`${excludedFiles.length} file(s) in test, generated, vendor, or build-output layers were excluded from the default product-source index.`)
      if (unreadableFiles > 0) warnings.push(`${unreadableFiles} source candidate(s) could not be read through the Core boundary.`)
      if (encodingFailures > 0) warnings.push(`${encodingFailures} source candidate(s) were not parsed because input was not valid UTF-8.`)
      if (truncatedFiles > 0) warnings.push(`${truncatedFiles} source file(s) landed at a read limit; parser output is partial and does not cover the complete file.`)
      if (sorted.length >= limits.maxFiles) limitsApplied.push('maxFiles')
      if (candidates.length === 0) warnings.push('No JS/TS source file was found in the Core-enumerated scope.')

      const parsed = sourceParser.analyzeSourceUnits(units, { maxRecords: limits.maxRecords })
      if (parsed.summary.omittedRecords > 0 || parsed.summary.filesOmitted > 0) {
        limitsApplied.push('maxRecords')
        warnings.push(`${parsed.summary.omittedRecords} detail record(s) and ${parsed.summary.filesOmitted} later file(s) were omitted by maxRecords.`)
      }
      const uniqueLimits = [...new Set(limitsApplied)]
      const status = units.length === 0
        ? 'UNSUPPORTED'
        : parsed.analysis.status === 'PARTIAL' || warnings.length > 0 || uniqueLimits.length > 0
          ? 'PARTIAL'
          : 'COMPLETE'
      const data = {
        ...parsed,
        summary: {
          ...parsed.summary,
          filesListed: sorted.length,
          sourceCandidates: candidates.length,
          unsupportedLanguageFiles: unsupportedLanguageCount,
          filesExcludedByLayer: excludedFiles.length,
          excludedFileDetailsOmitted: Math.max(0, excludedFiles.length - 100),
          unreadableFiles,
          invalidEncodingFiles: encodingFailures,
          bytesRead,
          truncatedFiles,
          recordsEmitted: parsed.summary.recordsEmitted,
          filesOmitted: parsed.summary.filesOmitted,
        },
        unsupportedFiles: unsupportedFiles.slice(0, 50),
        excludedFiles: excludedFiles.slice(0, 100),
        analysis: {
          ...parsed.analysis,
          status,
          warnings: [...new Set([...parsed.analysis.warnings, ...warnings])].slice(0, 100),
          limitsApplied: uniqueLimits,
          extraction: 'IN_MEMORY_ONLY_NO_CODE_EXECUTED',
        },
      }
      const boundedData = fitSourceResult(data, limits.maxResultBytes)
      checkAbort(input.env, capability)
      const summary = `S2 解析 ${boundedData.summary.filesParsed}/${boundedData.summary.sourceCandidates} 个 JS/TS 候选文件，得到 ${boundedData.summary.symbols} 个符号、${boundedData.summary.references} 个同文件引用；状态 ${boundedData.analysis.status}。`
      return {
        summary: sanitizeText(summary, 4000),
        findings: [],
        evidence: [
          makeEvidence('源码符号索引摘要', 'source-symbol-summary', JSON.stringify(boundedData.summary), { parser: sourceParser.SOURCE_PARSER_ID, parserVersion: sourceParser.SOURCE_PARSER_VERSION, status: boundedData.analysis.status }),
        ],
        data: boundedData,
        meta: {
          ...makeMeta(capability, 'source-symbol-ir', {
            analyzedBytes: bytesRead,
            source: 'workspace-read',
          truncated: truncatedFiles > 0 || boundedData.summary.resultTruncated === true,
          }, boundedData.analysis.warnings),
          parserId: SOURCE_PARSER_ID,
          parserVersion: sourceParser.SOURCE_PARSER_VERSION,
          supportLevel: 'S2',
          resultBudgetBytes: limits.maxResultBytes,
        },
      }
    },
  },
]

export default { domain: 'source', capabilities }
